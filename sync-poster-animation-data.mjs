import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const developmentFile = new URL('assets/development-pixel-manifest.json', import.meta.url);
const servicesFile = new URL('assets/service-animation-manifest.json', import.meta.url);
const output = new URL('poster-animation-data.js', import.meta.url);
const check = process.argv.includes('--check');
console.info('[0/3] 輸入：', fileURLToPath(developmentFile), fileURLToPath(servicesFile));
console.info('[0/3] 輸出：', fileURLToPath(output), check ? '比對模式' : '寫入模式');

const [development, services] = await Promise.all(
  [developmentFile, servicesFile].map(async file => JSON.parse(await readFile(file, 'utf8'))),
);
console.info('[1/3] 讀取四張海報的動畫規格。');
const script = '/* Generated by sync-poster-animation-data.mjs. */\n' +
  'globalThis.pixelPosterData = ' + JSON.stringify({ development, services: services.services }, null, 2) + ';\n';
console.info('[2/3] 已產生可直接隨首頁載入的動畫資料。');

if (check) {
  const current = (await readFile(output, 'utf8')).replaceAll('\r\n', '\n');
  if (current !== script) throw new Error('動畫資料已變更，請執行 node sync-poster-animation-data.mjs。');
} else {
  await writeFile(output, script, 'utf8');
}
console.info('[3/3]', check ? '動畫資料一致。' : '已寫入動畫資料。');
